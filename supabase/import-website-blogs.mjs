/**
 * One-off importer: push the 35 hand-written Markdown articles in
 * ~/Desktop/websiteblogsvoltairtech into the DB (and the chatbot RAG store) by
 * POSTing them to the site's admin-gated /api/blog endpoint — exactly the path
 * the admin panel / n8n use. Writing through the running dev server hits the
 * same Supabase project the live site + admin read from, so the posts show up
 * on both, and published posts are embedded so the bot can cite them.
 *
 * Usage (dev server running, admin key loaded):
 *   node --env-file=.env.local supabase/import-website-blogs.mjs --dry-run
 *   node --env-file=.env.local supabase/import-website-blogs.mjs
 *   SITE=https://voltairtech.com node --env-file=.env.local supabase/import-website-blogs.mjs
 */
import { readdir, readFile } from "node:fs/promises";
import { homedir } from "node:os";
import { join } from "node:path";

const SITE = process.env.SITE || "http://localhost:3000";
const KEY = process.env.ADMIN_API_KEY;
const BLOG_DIR =
  process.env.BLOG_DIR || join(homedir(), "Desktop", "websiteblogsvoltairtech");
const DRY_RUN = process.argv.includes("--dry-run");

if (!KEY && !DRY_RUN) {
  console.error("Set ADMIN_API_KEY (run with --env-file=.env.local).");
  process.exit(1);
}

const ACRONYMS = new Set([
  "ai", "hr", "it", "nlp", "rpa", "roi", "kpi", "crm", "erp", "iot",
  "ml", "b2b", "b2c", "api", "upi", "seo", "geo", "aeo", "csat", "aht", "saas",
]);

/** Title-case a tag while preserving acronyms, WhatsApp, hyphens and ampersands. */
function fmtTag(s) {
  return s
    .trim()
    .split(/\s+/)
    .map((word) =>
      word
        .split("-")
        .map((part) => {
          const low = part.toLowerCase();
          if (ACRONYMS.has(low)) return low.toUpperCase();
          if (low === "whatsapp") return "WhatsApp";
          if (!/[a-z]/i.test(part)) return part; // "&" and friends
          return part.charAt(0).toUpperCase() + part.slice(1);
        })
        .join("-"),
    )
    .join(" ");
}

/** Parse `---` frontmatter + body out of a raw Markdown string. */
function parseFrontmatter(raw) {
  const meta = {};
  let body = raw;
  if (raw.startsWith("---")) {
    const end = raw.indexOf("\n---", 3);
    if (end !== -1) {
      const fm = raw.slice(3, end).trim();
      body = raw.slice(end + 4);
      for (const line of fm.split("\n")) {
        const i = line.indexOf(":");
        if (i === -1) continue;
        meta[line.slice(0, i).trim()] = line.slice(i + 1).trim();
      }
    }
  }
  return { meta, body };
}

/** Strip the leading duplicate H1 (the page renders the title itself) and the
 *  trailing internal footer (`*Word count`, `*Generated by`, `*Date:`). */
function cleanBody(body) {
  const lines = body.replace(/\r\n/g, "\n").split("\n");
  while (lines.length && lines[0].trim() === "") lines.shift();
  if (lines.length && /^#\s+/.test(lines[0])) {
    lines.shift();
    while (lines.length && lines[0].trim() === "") lines.shift();
  }
  const footer = /^\*\s?(word count|generated by|date:)/i;
  while (lines.length) {
    const last = lines[lines.length - 1].trim();
    if (last === "" || footer.test(last)) lines.pop();
    else break;
  }
  return lines.join("\n").trim();
}

function slugFromFile(name) {
  return name
    .replace(/\.md$/i, "")
    .replace(/^\d+_/, "")
    .replace(/_/g, "-")
    .toLowerCase();
}

function tagsFor(keywords) {
  const kw = (keywords || "")
    .split(",")
    .map((k) => k.trim())
    .filter(Boolean);
  if (!kw.length) return [];
  // Industry use-cases lead with the generic "AI automation"; topic articles
  // lead with their own primary tag.
  const isUseCase = (kw[0] || "").toLowerCase() === "ai automation";
  const picked = isUseCase ? [kw[1], "AI Automation"] : [kw[0], kw[1]];
  return [...new Set(picked.filter(Boolean).map(fmtTag))];
}

async function build() {
  const files = (await readdir(BLOG_DIR))
    .filter((f) => f.toLowerCase().endsWith(".md"))
    .sort();
  // file 01 newest (top of the index) -> spaced 1 min apart, all in the past.
  const base = Date.now() - 2 * 60 * 1000;
  return Promise.all(
    files.map(async (file, i) => {
      const raw = await readFile(join(BLOG_DIR, file), "utf8");
      const { meta, body } = parseFrontmatter(raw);
      const title = meta.title || file.replace(/\.md$/i, "");
      const description = meta.description || "";
      return {
        slug: slugFromFile(file),
        title,
        status: "published",
        author: "Voltair Tech",
        tags: tagsFor(meta.keywords),
        excerpt: description || null,
        seo: { title, description },
        body_md: cleanBody(body),
        published_at: new Date(base - i * 60 * 1000).toISOString(),
        _file: file,
      };
    }),
  );
}

const posts = await build();

if (DRY_RUN) {
  console.log(`Parsed ${posts.length} posts from ${BLOG_DIR}\n`);
  for (const p of posts) {
    console.log(`• ${p.slug}`);
    console.log(`    title : ${p.title}`);
    console.log(`    tags  : [${p.tags.join(", ")}]`);
    console.log(`    pub   : ${p.published_at}`);
    console.log(`    body  : ${p.body_md.length} chars, starts "${p.body_md.slice(0, 60).replace(/\n/g, " ")}…"`);
  }
  process.exit(0);
}

let ok = 0;
for (const { _file, ...post } of posts) {
  const res = await fetch(`${SITE}/api/blog`, {
    method: "POST",
    headers: { "content-type": "application/json", "x-admin-key": KEY },
    body: JSON.stringify(post),
  });
  const text = await res.text();
  if (res.ok) {
    ok += 1;
    console.log(`✓ ${post.slug}  (${res.status})`);
  } else {
    console.error(`✗ ${post.slug}  (${res.status})  ${text}`);
  }
}
console.log(`\nDone: ${ok}/${posts.length} posted to ${SITE}/api/blog`);
process.exit(ok === posts.length ? 0 : 1);
